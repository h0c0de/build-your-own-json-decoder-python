# buat_tabel.py — reformatter tabel parsing JSON.
#
# Panduan cheery/json-algorithm menegaskan: ambil daftar
# 'states', 'gotos', 'catcode' dari json.txt, dan BILA
# formatnya tidak cocok, tulis reformatter — JANGAN format
# ulang dengan tangan. Skrip inilah reformatter itu:
# membaca json.txt (berkas hulu, MIT, Henri Tuhola) dan
# menulis tabel.py yang siap diimpor.
#
# Jalankan:  python3 buat_tabel.py
import pathlib

sini = pathlib.Path(__file__).parent

ns = {}
exec((sini / "json.txt").read_text(encoding="utf-8"), ns)
states, gotos, catcode = ns["states"], ns["gotos"], ns["catcode"]
assert len(states) == len(gotos) == 42, "jumlah state di luar dugaan"
assert all(len(baris) == 28 for baris in states), "lebar tabel berubah"
assert len(catcode) == 127, "panjang catcode berubah"

baris = [
    "# tabel.py — DIBANGKITKAN oleh buat_tabel.py dari json.txt.",
    "# JANGAN disunting dengan tangan; sunting json.txt atau",
    "# bangun ulang tabelnya (bangun_tabel.py), lalu jalankan",
    "# buat_tabel.py lagi.",
    "#",
    "# Tabel parsing JSON dari proyek cheery/json-algorithm",
    "# (MIT, Copyright (c) 2016 Henri Tuhola) — dibangun dari",
    "# diagram railroad di http://json.org/ oleh program",
    "# build_tables.py hulu. Komentar asal json.txt:",
    "# 'generated by build_tables.py program:",
    "#  http://github.com/cheery/json_algorithm'",
    "",
    "states = [",
]
for row in states:
    baris.append(f"    {row!r},")
baris.append("]")
baris.append("")
baris.append(f"gotos = {gotos!r}")
baris.append("")
baris.append(f"catcode = {catcode!r}")
baris.append("")

(sini / "tabel.py").write_text("\n".join(baris), encoding="utf-8")
print(f"tabel.py ditulis: {len(states)} state x "
      f"{len(states[0])} catcode, {len(gotos)} goto, "
      f"{len(catcode)} catcode")
